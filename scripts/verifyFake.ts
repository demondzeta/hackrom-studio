import { readFileSync } from "node:fs";
import { unzipSync } from "fflate";
import { RomSet } from "../src/core/romset";
import { detectProfile } from "../src/games/profiles";
import { kofBanks, listActs, parseAct, actFrames, graphEntry, decodeSpriteDef, scanCommandTables, parseCommand, inputToArrows, scanImageTables, serializeAct } from "../src/games/kofEngine";
import { readHeader, findMainLoops, planHook, findFreeSpace, findMoveLImmToDisp } from "../src/core/analysis";
import { routineToAsm } from "../src/core/relocate";
import { assemble } from "../src/core/m68k/asm";
import { exportZip, makeIps } from "../src/core/io";
const z = unzipSync(readFileSync(process.argv[2]));
const rs = RomSet.fromFiles("kof97", Object.entries(z).map(([name, data]) => ({ name, data })));
const p = detectProfile(rs);
console.log("profile", p.id, "p1", rs.p1, "swapped", rs.files[rs.p1].swapped, "banks", rs.banks.length);
const h = readHeader(rs); console.log("header", h.valid, h.ngh.toString(16), h.entries.map(e => e.name + "=" + e.target?.toString(16)).join(" "));
const k = p.kof!; const b = kofBanks(rs, k)!; console.log("banks", b);
const acts = listActs(rs, k, b.actBank, 0); console.log("acts", acts.length, acts.slice(-2));
const s = parseAct(rs, b.actBank, 0x212abe); console.log("script size", s.size, s.cmds.map(c => c.t).join(","));
const fr = actFrames(s); console.log("frames", fr.map(f => `${f.cmd.frameId.toString(16)}:${f.cmd.dur}:${f.activeBoxes.map(x => x.type.toString(16)).join("/")}`).join(" "));
console.log("roundtrip", Buffer.from(serializeAct(s.cmds)).equals(Buffer.from(rs.readBytes(0x212abe, s.size, b.actBank))));
const g = graphEntry(rs, k, b.graphBank, 0, 0xe1); console.log("graph", g);
const def = decodeSpriteDef(rs, b.graphBank, rs.read32(0x2536c6 + g.image * 4, b.graphBank), "colmajor"); console.log("def", def.cols, def.rows, def.baseTile.toString(16));
console.log("imgTables", scanImageTables(rs, b.graphBank).slice(0, 3));
const ct = scanCommandTables(rs, k.commandArea!); console.log("cmd tables", ct.map(x => x.toString(16)));
const cd = parseCommand(rs, rs.read32(0xa6e38 + 5 * 4)); console.log("cmd", cd.steps.map(x => inputToArrows(x.input)).join(" "), cd.window);
const ml = findMainLoops(rs, [0x9c38]); console.log("loops", ml.loops.slice(0, 3).map(l => l.start.toString(16) + "-" + l.end.toString(16) + " " + l.score + " " + l.reasons.join("|")));
const free = findFreeSpace(rs.files[rs.p1].data, 256); console.log("free", free.slice(0, 2).map(f => f.offset.toString(16) + ":" + f.length));
const plan = planHook(rs, 0x9c44, free[0].offset, "move.b #$60,$10A83A", true); console.log("hook ok", plan.ok, plan.errors, plan.displaced.map(d => d.text));
console.log(plan.listing);
const sites = findMoveLImmToDisp(rs.files[rs.p1].data, 0x198); console.log("routine sites", sites.map(s => s.addr.toString(16) + "->" + s.value.toString(16)));
const r = routineToAsm(rs.reader(0), 0x2feda); console.log(r.source); console.log("warn", r.warnings);
const re = assemble(r.source, 0x0f0000); console.log("reasm errors", re.errors, re.bytes.length);
rs.write(rs.p1, 0x9c44, [0x4e, 0x71]); const ips = makeIps(rs, rs.p1); console.log("ips bytes", ips.length);
const zz = exportZip(rs).zip; const back = unzipSync(zz); console.log("export p1 equals orig except edit:", back["232-p1.p1"].length, back["232-p1.p1"][0x9c45], back["232-p1.p1"][0x9c44]);
